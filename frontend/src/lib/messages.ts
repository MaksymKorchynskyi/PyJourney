const ukrainianRules = new Intl.PluralRules("uk");

function ukCount(count: number, one: string, few: string, many: string) {
  const rule = ukrainianRules.select(count);
  return `${count} ${rule === "one" ? one : rule === "few" ? few : many}`;
}

